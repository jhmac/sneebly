interface UserAction {
  id: string;
  title: string;
  message: string;
  prompt?: string;
  timestamp: string;
  dismissed: boolean;
}

const userActions: UserAction[] = [];

export function writeUserActionNeeded(title: string, message: string, prompt?: string): void {
  const action: UserAction = {
    id: `action-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
    title,
    message,
    prompt,
    timestamp: new Date().toISOString(),
    dismissed: false,
  };
  userActions.push(action);
  logActivity('error', `ACTION NEEDED: ${title} — ${message}`);
  console.log(`[Autonomy] USER ACTION NEEDED: ${title}`);
}

export function getUserActions(): UserAction[] {
  return userActions.filter(a => !a.dismissed);
}

export function dismissUserAction(id: string): boolean {
  const action = userActions.find(a => a.id === id);
  if (action) { action.dismissed = true; return true; }
  return false;
}

