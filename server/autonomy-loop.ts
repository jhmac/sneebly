async function runPostBuildUiScan(label: string): Promise<void> {
  try {
    const { generateUiSpec } = await import('./ui-spec-generator');
    const { runUiCrawl, isCrawlRunning, loadUiHealth } = await import('./ui-crawler');
    logActivity('info', `Post-build UI scan triggered (client files modified in ${label})`);
    console.log(`[Autonomy/UI] ${label}: client files modified — running post-build UI spec + scan...`);
    await generateUiSpec();

    // If a crawl is already in progress, wait for it to finish (up to 90s) then use its result
    if (isCrawlRunning()) {
      console.log('[Autonomy/UI] Another crawl is in progress — waiting up to 90s for it to finish...');
      const deadline = Date.now() + 90_000;
      while (isCrawlRunning() && Date.now() < deadline) {
        await new Promise(r => setTimeout(r, 2500));
      }
      const existingReport = loadUiHealth();
      if (existingReport) {
        const summary = `UI Scan (reused): ${existingReport.routesPassed} passed, ${existingReport.routesFailed} failed, ${existingReport.totalErrors} errors`;
        logActivity(existingReport.routesFailed > 0 ? 'warning' : 'success', summary);
        logToDaily(summary);
        console.log(`[Autonomy/UI] ${summary}`);
        attachUiScanToJournal(existingReport);
      } else {
        console.log('[Autonomy/UI] Timed out waiting for crawl — journal entry will have no UI scan result');
      }
      return;
    }

    const report = await runUiCrawl({ regenerateSpec: false });
    const summary = `UI Scan: ${report.routesPassed} passed, ${report.routesFailed} failed, ${report.totalErrors} errors`;
    logActivity(report.routesFailed > 0 ? 'warning' : 'success', summary);
    logToDaily(summary);
    console.log(`[Autonomy/UI] ${summary}`);
    attachUiScanToJournal(report);
    if (report.routesFailed > 0) {
      console.log(`[Autonomy/UI] WARNING: ${report.routesFailed} route(s) failed — blockers created for critical failures`);
    }
  } catch (uiErr: any) {
    console.log(`[Autonomy/UI] Post-build UI scan failed (non-fatal): ${uiErr.message}`);
  }
}

async function runCycle(): Promise<string> {
  if (state.stopRequested) {
    state.stopRequested = false;
    state.running = false;
    if (loopInterval) { clearInterval(loopInterval); loopInterval = null; }
    console.log("[Autonomy] Stop request honored — loop terminated");
    return "stopped";
  }
  if (state.paused) return "paused";
  if (!checkBudget()) {
    console.log("[Autonomy] Budget exceeded — STOPPING loop (not just pausing)");
    stopAutonomyLoop();
    writeUserActionNeeded("Budget limit reached", "Your AI spending limit has been reached. The autonomy loop has been stopped to prevent further charges. You can increase the budget on the Budget page and restart autonomy.");
    return "budget-exceeded";
  }
  if (state.currentCycle >= MAX_CYCLES_PER_SESSION) {
    state.paused = true;
    return "max-cycles-reached";
  }

  const now = Date.now();
  if (now - lastCycleStartTime < MIN_CYCLE_INTERVAL_MS) return "rate-limited";
  lastCycleStartTime = now;

  state.currentCycle++;
  state.totalCycles++;
  installedPackagesThisCycle.clear();
  console.log(`[Autonomy] === Cycle ${state.currentCycle} ===`);
  logActivity('info', `Starting cycle ${state.currentCycle}`);

  if (!currentJournal) currentJournal = loadJournal() || createJournal();
  const costBefore = getCostSummary().totalAllTime;

  const entry: JournalEntry = {
    cycle: state.currentCycle,
    timestamp: new Date().toISOString(),
    result: "unknown",
    stepDescription: null,
    filesModified: [],
    error: null,
    costThisCycle: 0,
    usedOpus: false,
    verificationPassed: null,
    autoFixerTriggered: false,
    retryContext: null,
  };

  const failureContext = getRecentFailureContext(currentJournal);
  if (failureContext) {
    entry.retryContext = failureContext;
  }

  try {
    logActivity('thinking', 'Running health check...');
    const healthy = await quickHealthCheck();
    if (!healthy) {
      pushError(`Cycle ${state.currentCycle}: Server not healthy`);
      logActivity('error', 'Server health check failed');
      if (state.errors.length >= MAX_ERRORS_BEFORE_PAUSE) state.paused = true;
      entry.result = "unhealthy";
      entry.error = "Server not healthy";
      entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
      addJournalEntry(currentJournal, entry);
      return "unhealthy";
    }
    logActivity('success', 'Health check passed');

    let plan = loadCurrentPlan();
    if (!plan || plan.status !== "active") {
      console.log("[Autonomy] Opus generating new plan...");
      logActivity('thinking', 'Opus is generating a new plan...');
      try {
        plan = await generatePlan(failureContext || undefined);
        logActivity('success', `Plan created: "${plan.goal}" (${plan.steps.length} steps)`);
        console.log(`[Autonomy] Plan created: "${plan.goal}" with ${plan.steps.length} steps (statuses: ${plan.steps.map(s => s.status).join(", ")})`);
      } catch (error: any) {
        pushError(`Cycle ${state.currentCycle}: Planner failed — ${error.message}`);
        logActivity('error', `Planner failed: ${error.message}`);
        entry.result = "planner-failed";
        entry.error = error.message;
        entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
        addJournalEntry(currentJournal, entry);
        return "planner-failed";
      }
    } else {
      console.log(`[Autonomy] Existing plan: "${plan.goal}" status=${plan.status}, steps: ${plan.steps.map(s => `${s.id}:${s.status}`).join(", ")}`);
      const stuckSteps = plan.steps.filter(s => s.status === "in_progress");
      if (stuckSteps.length > 0) {
        console.log(`[Autonomy] Recovering ${stuckSteps.length} stuck in_progress step(s) back to pending`);
        for (const s of stuckSteps) {
          s.status = "pending";
        }
        savePlan(plan);
      }
    }

    const nextStep = getNextStep();
    if (!nextStep) {
      console.log(`[Autonomy] getNextStep() returned null — plan steps: ${plan.steps.map(s => `${s.id}(${s.status})`).join(", ")}`);
      const filesBuiltThisPlan = currentJournal
        ? Array.from(new Set(currentJournal.entries.flatMap(e => e.filesModified))).length
        : 0;

      plan.status = "completed";
      savePlan(plan);

      if (filesBuiltThisPlan === 0) {
        consecutiveEmptyPlans++;
        console.log(`[Autonomy] Plan had zero productive work (${consecutiveEmptyPlans} consecutive empty plans)`);

        if (consecutiveEmptyPlans >= MAX_CONSECUTIVE_EMPTY_PLANS) {
          console.log(`[Autonomy] ${consecutiveEmptyPlans} consecutive empty plans — pausing to avoid wasting budget`);
          state.paused = true;
          entry.result = "paused-no-work";
          entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
          addJournalEntry(currentJournal!, entry);
          return "paused-no-work";
        }

        entry.result = "plan-empty-skipped";
        entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
        addJournalEntry(currentJournal!, entry);
        return "plan-empty-skipped";
      }

      consecutiveEmptyPlans = 0;
      console.log("[Autonomy] Plan complete — Opus reviewing before next plan...");

      try {
        await markGoalComplete(plan.goal);
        generateProgressReport();
      } catch (e) {
        console.log('[sneebly] Could not mark goal:', (e as Error).message);
      }

      const review = await opusReviewPlan(plan, currentJournal!);

      if (review.needsRefactoring && review.refactorInstructions.length > 0) {
        console.log(`[Autonomy] Opus found ${review.refactorInstructions.length} issue(s) — auto-refactoring...`);
        const refactorResult = await autoRefactor(review);

        if (refactorResult.filesModified.length > 0) {
          console.log(`[Autonomy] Refactored ${refactorResult.filesModified.length} file(s) — verifying...`);
          const verifyResult = await verifyChanges(refactorResult.filesModified);
          if (!verifyResult.allPassed) {
            console.log("[Autonomy] Refactor verification failed — rolling back refactor changes");
            rollbackFiles(refactorResult.filesModified);
          } else {
            console.log("[Autonomy] Refactor verified successfully");
          }
        }

        writePlanReviewSummary(plan, currentJournal!, review);
      } else {
        console.log("[Autonomy] Opus review: code looks good — continuing to next plan");
        writePlanReviewSummary(plan, currentJournal!, review);
      }

      // ─── Playwright e2e suite after every plan ──────────────────────────
      console.log("[Autonomy] Running Playwright e2e suite...");
      logActivity('thinking', 'Running Playwright e2e tests after plan completion...');
      try {
        const pw = await runPlaywrightSuite();
        const secs = (pw.durationMs / 1000).toFixed(1);
        if (pw.success) {
          console.log(`[Autonomy] Playwright: ${pw.passed}/${pw.total} passed (${secs}s) ✓`);
          logActivity('success', `Playwright: ${pw.passed}/${pw.total} tests passed (${secs}s)`);
        } else {
          console.log(`[Autonomy] Playwright: ${pw.failed} test(s) FAILED — ${pw.passed}/${pw.total} passed (${secs}s) — triggering auto-fix...`);
          logActivity('warning', `Playwright: ${pw.failed} test(s) failed — ${pw.passed}/${pw.total} passed (${secs}s) — attempting auto-fix`, pw.output.slice(-800));
          await autoFixPlaywrightFailures(pw);
        }
      } catch (pwErr) {
        console.log(`[Autonomy] Playwright suite error: ${(pwErr as Error).message}`);
        logActivity('error', `Playwright suite error: ${(pwErr as Error).message}`);
      }
      // ────────────────────────────────────────────────────────────────────

      console.log("[Autonomy] Plan reviewed — will generate next plan on next cycle");

      entry.result = "plan-complete-reviewed";
      entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
      addJournalEntry(currentJournal!, entry);
      return "plan-complete-reviewed";
    }

    if (state.stopRequested) {
      state.stopRequested = false;
      state.running = false;
      if (loopInterval) { clearInterval(loopInterval); loopInterval = null; }
      entry.result = "stopped";
      entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
      addJournalEntry(currentJournal, entry);
      return "stopped";
    }
    if (!checkBudget()) {
      stopAutonomyLoop();
      writeUserActionNeeded("Budget limit reached", "Budget hit before building step. Loop stopped.");
      entry.result = "budget-exceeded";
      entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
      addJournalEntry(currentJournal, entry);
      return "budget-exceeded";
    }

    entry.stepDescription = nextStep.description;
    console.log(`[Autonomy] Opus building: ${nextStep.description}`);
    logActivity('thinking', `Building: ${nextStep.description}`);

    let stepContext = failureContext || undefined;
    if ((nextStep as any).failCount && (nextStep as any).failCount > 0) {
      const allErrors: string[] = (nextStep as any).errors || [];
      const errHistory = allErrors.length > 0
        ? allErrors.map((e: string, i: number) => `Attempt ${i + 1}: ${e}`).join("\n")
        : ((nextStep as any).lastError || "(no details)");
      const retryNote = `\n\nIMPORTANT — This step is being RETRIED (attempt ${((nextStep as any).failCount || 0) + 1}).\n## Full Error History (do NOT repeat these mistakes):\n${errHistory}\nTry a completely different strategy to accomplish the goal.`;
      stepContext = (stepContext || "") + retryNote;
    }

    const buildResult = await executeStep({ ...nextStep, failCount: (nextStep as any).failCount || 0 }, stepContext);

    // Per-cycle cost safety cap — stops runaway Opus chains before they burn the budget
    const cycleCostSoFar = getCostSummary().totalAllTime - costBefore;
    if (cycleCostSoFar > MAX_COST_PER_CYCLE) {
      console.log(`[Autonomy] CYCLE COST CAP hit — $${cycleCostSoFar.toFixed(3)} this cycle (cap: $${MAX_COST_PER_CYCLE}). Stopping cycle.`);
      logToDaily(`Cycle ${state.currentCycle} aborted: cost cap exceeded ($${cycleCostSoFar.toFixed(3)} > $${MAX_COST_PER_CYCLE})`);
      writeUserActionNeeded("Cycle cost cap hit", `A single autonomy cycle spent $${cycleCostSoFar.toFixed(2)} — over the $${MAX_COST_PER_CYCLE} per-cycle limit. The step "${nextStep.description}" may be unusually expensive. Consider increasing MAX_COST_PER_CYCLE in autonomy-loop.ts or check if an Opus escalation loop is happening.`);
      if (buildResult.filesModified.length > 0) rollbackFiles(buildResult.filesModified);
      entry.result = "cycle-cost-cap";
      entry.error = `Cycle cost cap: $${cycleCostSoFar.toFixed(3)} > $${MAX_COST_PER_CYCLE}`;
      entry.costThisCycle = cycleCostSoFar;
      addJournalEntry(currentJournal, entry);
      return "error";
    }

    if (buildResult.success && buildResult.skipReason) {
      console.log(`[Autonomy] Step "${nextStep.id}" auto-skipped (pre-existence): ${buildResult.skipReason}`);
      logActivity('info', `Step auto-skipped: ${buildResult.skipReason}`);
      markStepDone(nextStep.id);
      entry.result = "skipped-preexistence";
      entry.skipReason = buildResult.skipReason;
      entry.filesModified = [];
      entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
      addJournalEntry(currentJournal, entry);
      return "success";
    }

    if (!buildResult.success) {
      if (buildResult.patchStats && buildResult.patchStats.misses > 0) {
        const s = buildResult.patchStats;
        logActivity('warning', `Patch miss: ${s.misses} hunk(s) not found, ${s.hits} applied (patch×${s.patchActions} replace×${s.replaceActions} create×${s.createActions}) — step will retry`, `step: ${nextStep.id}`);
      }
      logActivity('error', `Build failed: ${buildResult.error || 'unknown error'}`, undefined, buildResult.filesModified);

      const missingPkg = buildResult.error ? extractMissingPackageFromError(buildResult.error) : null;
      if (missingPkg && !installedPackagesThisCycle.has(missingPkg)) {
        installedPackagesThisCycle.add(missingPkg);
        console.log(`[Autonomy] "Cannot find module" error detected — installing "${missingPkg}" and retrying step...`);
        logActivity('info', `Auto-installing missing package: ${missingPkg}`);
        const installResult = await runPackageInstall(missingPkg);
        if (installResult.success) {
          logActivity('success', `Installed ${missingPkg} — retrying step`);
          console.log(`[Autonomy] Installed ${missingPkg} — retrying step "${nextStep.id}"`);
          const retryResult = await executeStep({ ...nextStep, failCount: (nextStep as any).failCount || 0 }, stepContext);
          if (retryResult.success) {
            entry.filesModified = retryResult.filesModified;
            entry.usedOpus = !!retryResult.usedOpus;
            if (retryResult.model) entry.model = retryResult.model;
            if (retryResult.routerReason) entry.routerReason = retryResult.routerReason;
            state.filesModified.push(...retryResult.filesModified);
            markStepDone(nextStep.id);
            state.errors = [];
            entry.result = "success";
            entry.verificationPassed = true;
            entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
            addJournalEntry(currentJournal, entry);
            return "success";
          }
          console.log(`[Autonomy] Retry after install still failed: ${retryResult.error}`);
        } else {
          logActivity('warning', `Failed to install ${missingPkg}: ${installResult.stderr?.slice(0, 100)}`);
        }
      }

      if (buildResult.filesModified.length > 0) {
        console.log("[Autonomy] Build failed with partial changes — rolling back step files...");
        logActivity('warning', `Rolling back ${buildResult.filesModified.length} file(s)`, undefined, buildResult.filesModified);
        const rolledBack = rollbackFiles(buildResult.filesModified);
        if (rolledBack.length > 0) {
          console.log(`[Autonomy] Rolled back ${rolledBack.length} file(s): ${rolledBack.join(", ")}`);
        }
      }

      pushError(`Cycle ${state.currentCycle}: Build failed — ${buildResult.error}`);
      if (buildResult.model) entry.model = buildResult.model;
      if (buildResult.routerReason) entry.routerReason = buildResult.routerReason;

      markStepFailed(nextStep.id, buildResult.error || "Build produced no changes");

      const planAfterFail = loadCurrentPlan();
      const stepAfterFail = planAfterFail?.steps.find(s => s.id === nextStep.id);
      if (stepAfterFail?.status === "pending") {
        console.log(`[Autonomy] Step "${nextStep.id}" will be retried next cycle (attempt ${stepAfterFail.failCount || 1})`);
      } else if (stepAfterFail?.status === "skipped") {
        console.log(`[Autonomy] Step "${nextStep.id}" about to be skipped — escalating to Opus...`);
        const escalationResult = await escalateStepToOpus(stepAfterFail || nextStep, buildResult.error || "Build failed");
        if (escalationResult.solved) {
          console.log(`[Autonomy] Opus SOLVED step "${nextStep.id}" — ${escalationResult.filesModified.length} file(s) modified`);
          markStepDone(nextStep.id);
          entry.filesModified = escalationResult.filesModified;
          entry.usedOpus = true;
          entry.model = "claude-opus-4-6";
          entry.routerReason = "Opus max: escalation after exhausting retries";
          entry.result = "success";
          state.filesModified.push(...escalationResult.filesModified);
          state.errors = [];
          entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
          addJournalEntry(currentJournal, entry);
          return "success";
        }
        console.log(`[Autonomy] Opus couldn't solve step either: ${escalationResult.reason}`);
        state.errors = [];
      }

      entry.result = "build-failed";
      entry.error = buildResult.error || "Build produced no changes";
      entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
      addJournalEntry(currentJournal, entry);
      return "build-failed";
    }

    entry.filesModified = buildResult.filesModified;
    entry.usedOpus = !!buildResult.usedOpus;
    if (buildResult.model) entry.model = buildResult.model;
    if (buildResult.routerReason) entry.routerReason = buildResult.routerReason;
    state.filesModified.push(...buildResult.filesModified);

    if (buildResult.filesModified.length > 0) {
      logActivity('thinking', `Verifying changes (${buildResult.filesModified.length} file(s))...`, undefined, buildResult.filesModified);
      console.log("[Autonomy] Quick-verifying step changes...");
      const stepVerify = await quickStepVerify(buildResult.filesModified);

      if (!stepVerify.passed) {
        logActivity('error', `Verification failed: ${stepVerify.errors[0]}`, undefined, buildResult.filesModified);
        console.log(`[Autonomy] Step verification issues: ${stepVerify.errors.join("; ")}`);

        const verifyErrorText = stepVerify.errors.join("; ");
        const missingPkgFromVerify = extractMissingPackageFromError(verifyErrorText);
        if (missingPkgFromVerify && !installedPackagesThisCycle.has(missingPkgFromVerify)) {
          installedPackagesThisCycle.add(missingPkgFromVerify);
          console.log(`[Autonomy] "Cannot find module" in verify — installing "${missingPkgFromVerify}" and retrying step...`);
          logActivity('info', `Auto-installing missing package from verify error: ${missingPkgFromVerify}`);
          const pkgInstall = await runPackageInstall(missingPkgFromVerify);
          if (pkgInstall.success) {
            logActivity('success', `Installed ${missingPkgFromVerify} — retrying step after verify failure`);
            const verifyRetryResult = await executeStep({ ...nextStep, failCount: (nextStep as any).failCount || 0 }, stepContext);
            if (verifyRetryResult.success) {
              entry.filesModified = verifyRetryResult.filesModified;
              entry.usedOpus = !!verifyRetryResult.usedOpus;
              if (verifyRetryResult.model) entry.model = verifyRetryResult.model;
              if (verifyRetryResult.routerReason) entry.routerReason = verifyRetryResult.routerReason;
              state.filesModified.push(...verifyRetryResult.filesModified);
              markStepDone(nextStep.id);
              state.errors = [];
              entry.result = "success";
              entry.verificationPassed = true;
              entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
              addJournalEntry(currentJournal, entry);
              return "success";
            }
          }
        }

        logActivity('warning', `Rolling back ${buildResult.filesModified.length} file(s)`);
        console.log("[Autonomy] Rolling back step files...");
        const rolledBack = rollbackFiles(buildResult.filesModified);
        if (rolledBack.length > 0) {
          console.log(`[Autonomy] Rolled back ${rolledBack.length} file(s): ${rolledBack.join(", ")}`);
        }

        markStepFailed(nextStep.id, `Step verification failed: ${stepVerify.errors.slice(0, 3).join("; ")}`);

        const planAfterVerifyFail = loadCurrentPlan();
        const stepAfterVerifyFail = planAfterVerifyFail?.steps.find(s => s.id === nextStep.id);
        if (stepAfterVerifyFail?.status === "skipped") {
          console.log(`[Autonomy] Verify failed + max retries — escalating to Opus...`);
          const verifyEscalation = await escalateStepToOpus(stepAfterVerifyFail || nextStep, `Verification errors: ${stepVerify.errors.join("; ")}`);
          if (verifyEscalation.solved) {
            console.log(`[Autonomy] Opus SOLVED verification issue — ${verifyEscalation.filesModified.length} file(s)`);
            markStepDone(nextStep.id);
            entry.filesModified = verifyEscalation.filesModified;
            entry.usedOpus = true;
            entry.model = "claude-opus-4-6";
            entry.routerReason = "Opus max: escalation after verify failure exhausted retries";
            entry.result = "success";
            entry.verificationPassed = true;
            state.filesModified.push(...verifyEscalation.filesModified);
            state.errors = [];
            entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
            addJournalEntry(currentJournal, entry);
            return "success";
          }
        }

        pushError(`Cycle ${state.currentCycle}: Step verification failed — ${stepVerify.errors[0]}`);
        entry.result = "verify-failed";
        entry.error = `Step verification: ${stepVerify.errors.slice(0, 3).join("; ")}`;
        entry.verificationPassed = false;
        entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
        addJournalEntry(currentJournal, entry);
        return "verify-failed";
      }

      entry.verificationPassed = true;
    }

    const healthyAfterStep = await quickHealthCheck();
    if (!healthyAfterStep) {
      console.log("[Autonomy] Server unhealthy after step — rolling back...");
      if (buildResult.filesModified.length > 0) {
        rollbackFiles(buildResult.filesModified);
      }
      markStepFailed(nextStep.id, "Server became unhealthy after changes");
      entry.result = "verify-failed";
      entry.error = "Server became unhealthy after changes";
      entry.verificationPassed = false;
      entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
      addJournalEntry(currentJournal, entry);
      return "verify-failed";
    }

    state.errors = [];
    logActivity('success', `Step completed: ${nextStep.description}`, undefined, buildResult.filesModified);
    if (buildResult.patchStats) {
      const s = buildResult.patchStats;
      const actionSummary = [
        s.patchActions > 0 ? `patch×${s.patchActions}` : "",
        s.replaceActions > 0 ? `replace×${s.replaceActions}` : "",
        s.createActions > 0 ? `create×${s.createActions}` : "",
      ].filter(Boolean).join(", ") || "none";
      const hunkSummary = s.patchActions > 0 ? `, hunks applied: ${s.hits}, missed: ${s.misses}` : "";
      logActivity('info', `File actions: ${actionSummary}${hunkSummary}`, `step: ${nextStep.id}`);
    }
    entry.result = "success";
    entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
    addJournalEntry(currentJournal, entry);

    // Post-build UI scan: same guarantee as parallel cycle — run if client files were modified
    const cycleClientChanges = entry.filesModified.some(f =>
      f.startsWith("client/") || f.endsWith(".tsx") || f.endsWith(".jsx")
    );
    if (cycleClientChanges) {
      await runPostBuildUiScan('runCycle');
    }

    if (currentJournal.successCount > 0 && currentJournal.successCount % 5 === 0) {
      try {
        await runLearningCycle();
        console.log('[sneebly] Learning cycle completed');
      } catch (e) {
        console.log('[sneebly] Learning cycle skipped:', (e as Error).message);
      }
    }

    return "success";
  } catch (error: any) {
    if (error.name === 'BudgetExceeded') {
      console.log('[sneebly] Budget exceeded — STOPPING loop');
      stopAutonomyLoop();
      writeUserActionNeeded("Budget limit reached", "Your AI spending limit was hit mid-cycle. The autonomy loop has been stopped. Increase the budget on the Budget page and restart.");
      entry.result = "budget-exceeded";
      entry.error = "Budget exceeded — loop stopped";
      entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
      addJournalEntry(currentJournal, entry);
      return "error";
    }
    pushError(`Cycle ${state.currentCycle}: ${error.message}`);
    console.error(`[Autonomy] Cycle error:`, error);
    if (state.errors.length >= MAX_ERRORS_BEFORE_PAUSE) state.paused = true;
    entry.result = "error";
    entry.error = error.message;
    entry.costThisCycle = getCostSummary().totalAllTime - costBefore;
    addJournalEntry(currentJournal, entry);
    return "error";
  }
}

const MAX_PARALLEL_FEATURES = parseInt(process.env.SNEEBLY_MAX_PARALLEL_FEATURES || "2", 10);
const MAX_STEPS_PER_FEATURE = 8;

// Tracks which feature IDs are actively being built in the current session.
// Used to detect orphaned in_progress features (stuck from a crashed/restarted previous cycle).
const activelyBuildingFeatureIds = new Set<string>();

let cachedTscErrorCount = 0;
let cachedTscErrorText = "";

function countTscErrors(): number {
  try {
    const raw = execSync("npx tsc --noEmit 2>&1 || true", {
      timeout: 30000,
      cwd: process.cwd(),
      stdio: ["pipe", "pipe", "pipe"],
      encoding: "utf8",
    }) as unknown as string;
    cachedTscErrorText = raw;
    const count = (raw.match(/error TS\d+/g) || []).length;
    cachedTscErrorCount = count;
    return count;
  } catch {
    return cachedTscErrorCount;
  }
}

interface FeatureResult {
  featureId: string;
  success: boolean;
  stepsCompleted: number;
  filesModified: string[];
  cost: number;
  error?: string;
  tscErrorsDelta?: number;
  hypothesisChosen?: "A" | "B" | "opus" | "none";
  hypothesisAApproach?: string;
  hypothesisBApproach?: string;
}

async function executeFeaturePlan(
  featureId: string,
  featureTitle: string,
  featureDescription: string,
  options: { lastTestFailureContext?: string; preBuildPlan?: Plan; featureAttemptCount?: number } = {}
): Promise<FeatureResult> {
  const costBefore = getCostSummary().totalAllTime;
  // Fresh baseline so delta is accurate even on first/restart cycle
  let tscBefore = cachedTscErrorCount;
  try { tscBefore = countTscErrors(); } catch { /* use cached */ }
  const result: FeatureResult = { featureId, success: false, stepsCompleted: 0, filesModified: [], cost: 0 };

  try {
    const healthy = await quickHealthCheck();
    if (!healthy) {
      result.error = "Server not healthy before feature start";
      return result;
    }

    const featurePlanFile = path.join(process.cwd(), ".sneebly", `feature-plan-${featureId}.json`);

    const featurePrefix = featureId.replace(/[^a-z0-9]/gi, "-");
    let plan: Plan;

    if (options.preBuildPlan) {
      plan = {
        ...options.preBuildPlan,
        id: `${featurePrefix}-plan-${Date.now()}`,
        steps: options.preBuildPlan.steps.map((s, i) => ({
          ...s,
          id: `${featurePrefix}-${s.id || `step-${i + 1}`}`,
          // Preserve "done" status so resumed plans skip already-completed steps
          status: (s.status === "done" ? "done" : "pending") as "done" | "pending",
        })),
      };
    } else {
      plan = await generateFeaturePlan(featureTitle, featureDescription, {
        lastTestFailureContext: options.lastTestFailureContext,
        priorFailureCount: options.featureAttemptCount ? options.featureAttemptCount - 1 : 0,
      });
      plan = {
        ...plan,
        id: `${featurePrefix}-plan-${Date.now()}`,
        steps: plan.steps.map((s, i) => ({
          ...s,
          id: `${featurePrefix}-${s.id || `step-${i + 1}`}`,
        })),
      };
    }

    fs.mkdirSync(path.dirname(featurePlanFile), { recursive: true });
    fs.writeFileSync(featurePlanFile, JSON.stringify(plan, null, 2), "utf-8");

    logActivity('success', `Feature plan created: "${plan.goal}" (${plan.steps.length} steps)`);

    const FEATURE_BUDGET_CAP = 3.0;

    for (let i = 0; i < MAX_STEPS_PER_FEATURE; i++) {
      if (!checkBudget()) break;

      const featureCostSoFar = getCostSummary().totalAllTime - costBefore;
      if (featureCostSoFar >= FEATURE_BUDGET_CAP) {
        console.log(`[Autonomy/Roadmap] Feature "${featureTitle}" exceeded $${FEATURE_BUDGET_CAP} budget cap ($${featureCostSoFar.toFixed(2)}) — pausing`);
        result.error = `Feature budget cap of $${FEATURE_BUDGET_CAP} exceeded`;
        writeNeedsAttention(0, "feature-budget-exceeded", featureTitle, `Feature cost $${featureCostSoFar.toFixed(2)} exceeded $${FEATURE_BUDGET_CAP} cap`);
        break;
      }

      const nextStep = plan.steps.find(s => s.status === "pending");
      if (!nextStep) {
        plan.status = "completed";
        break;
      }

      nextStep.status = "in_progress";
      fs.writeFileSync(featurePlanFile, JSON.stringify(plan, null, 2), "utf-8");

      // Only escalate builder model if this specific step has previously failed.
      // A brand-new step (failCount=0) always starts with Sonnet; feature-level attempt count
      // is only used for steps that have already failed at least once in a prior plan cycle.
      const stepPriorFails = nextStep.failCount || 0;
      const baseFailCount = stepPriorFails > 0
        ? Math.max(stepPriorFails, (options.featureAttemptCount ?? 1) - 1)
        : 0;
      const buildResult = await executeStep(
        { id: nextStep.id, action: nextStep.action, filePath: nextStep.filePath, description: nextStep.description, failCount: baseFailCount },
        undefined
      );

      if (!buildResult.success) {
        if (buildResult.filesModified.length > 0) rollbackFiles(buildResult.filesModified);
        nextStep.status = "failed";
        nextStep.lastError = buildResult.error || "Build failed";
        fs.writeFileSync(featurePlanFile, JSON.stringify(plan, null, 2), "utf-8");
        break;
      }

      if (buildResult.filesModified.length > 0) {
        const stepVerify = await quickStepVerify(buildResult.filesModified);
        if (!stepVerify.passed) {
          rollbackFiles(buildResult.filesModified);
          nextStep.status = "failed";
          nextStep.lastError = `Verify failed: ${stepVerify.errors.slice(0, 2).join("; ")}`;
          fs.writeFileSync(featurePlanFile, JSON.stringify(plan, null, 2), "utf-8");
          break;
        }

        const healthyAfter = await quickHealthCheck();
        if (!healthyAfter) {
          rollbackFiles(buildResult.filesModified);
          nextStep.status = "failed";
          nextStep.lastError = "Server became unhealthy after step";
          fs.writeFileSync(featurePlanFile, JSON.stringify(plan, null, 2), "utf-8");
          break;
        }
      }

      nextStep.status = "done";
      result.stepsCompleted++;
      result.filesModified.push(...buildResult.filesModified.filter(f => !result.filesModified.includes(f)));
      fs.writeFileSync(featurePlanFile, JSON.stringify(plan, null, 2), "utf-8");
    }

    const allDone = plan.steps.every(s => s.status === "done" || s.status === "skipped");
    result.success = allDone && result.stepsCompleted > 0;
    result.cost = getCostSummary().totalAllTime - costBefore;

    if (result.success) {
      try {
        const tscAfter = countTscErrors();
        result.tscErrorsDelta = tscBefore - tscAfter;
        console.log(`[Autonomy/TSC] Feature "${featureTitle}" TSC delta: ${result.tscErrorsDelta >= 0 ? "+" : ""}${result.tscErrorsDelta} (before: ${tscBefore}, after: ${tscAfter})`);
      } catch { /* non-fatal */ }
    }

    return result;
  } catch (err: unknown) {
    result.error = err instanceof Error ? err.message : String(err);
    result.cost = getCostSummary().totalAllTime - costBefore;
    return result;
  }
}

function saveHypothesisSnapshot(files: string[], tag: string): string {
  const snapshotDir = path.join(process.cwd(), ".sneebly", "hypothesis-snapshots", tag);
  fs.mkdirSync(snapshotDir, { recursive: true });
  for (const file of files) {
    const fullPath = path.resolve(process.cwd(), file);
    if (fs.existsSync(fullPath)) {
      const safeName = file.replace(/[/\\]/g, "__");
      fs.copyFileSync(fullPath, path.join(snapshotDir, safeName));
    }
  }
  return snapshotDir;
}

function restoreHypothesisSnapshot(snapshotDir: string): void {
  if (!fs.existsSync(snapshotDir)) return;
  for (const file of fs.readdirSync(snapshotDir)) {
    const srcPath = path.join(snapshotDir, file);
    const relPath = file.replace(/__/g, "/");
    const destPath = path.resolve(process.cwd(), relPath);
    const destDir = path.dirname(destPath);
    if (!fs.existsSync(destDir)) fs.mkdirSync(destDir, { recursive: true });
    fs.copyFileSync(srcPath, destPath);
    console.log(`[Autonomy/Hypothesis] Restored: ${relPath}`);
  }
}

/**
 * Full hypothesis rollback:
 * 1. Restore modified files from builder backups (existing files that were changed).
 * 2. Delete newly created files — those with no backup (builder only backs up pre-existing files).
 * This prevents losing-hypothesis artifacts from contaminating the winner's state.
 */
function rollbackHypothesisFull(filesModified: string[]): void {
  if (filesModified.length === 0) return;
  const restoredFiles = rollbackFiles(filesModified);
  const restoredSet = new Set(restoredFiles);
  for (const f of filesModified) {
    if (!restoredSet.has(f)) {
      // No backup existed → file was newly created by this hypothesis; delete it
      const fullPath = path.resolve(process.cwd(), f);
      try {
        if (fs.existsSync(fullPath)) {
          fs.unlinkSync(fullPath);
          console.log(`[Autonomy/Hypothesis] Deleted new file from losing hypothesis: ${f}`);
        }
      } catch (err: any) {
        console.log(`[Autonomy/Hypothesis] Could not delete ${f}: ${err.message}`);
      }
    }
  }
}

async function runMultiHypothesisFeature(
  feature: Pick<RoadmapFeature, "id" | "title" | "description" | "lastTestResult">,
  lastTestFailureContext?: string,
  featureAttemptCount?: number
): Promise<FeatureResult> {
  console.log(`[Autonomy/Hypothesis] Running multi-hypothesis build for: ${feature.title}`);
  logActivity("info", `Multi-hypothesis build: ${feature.title}`);

  const ts = Date.now();
  const snapshotTagA = `${feature.id}-${ts}-A`;
  const snapshotTagB = `${feature.id}-${ts}-B`;

  // Fetch prior knowledge once and pass explicitly to both plan calls
  let priorKnowledge: Array<{ title: string; approach: string; qualityDelta: number }> = [];
  try {
    priorKnowledge = getRelevantKnowledge(feature.title, 5);
  } catch { /* non-fatal */ }

  const priorFailures = featureAttemptCount ? featureAttemptCount - 1 : 0;

  // --- Resume from interrupted plan if available, otherwise generate fresh plans ---
  const savedPlanPath = path.join(process.cwd(), ".sneebly", `feature-plan-${feature.id}.json`);
  let resumedPlan: Plan | null = null;
  try {
    if (fs.existsSync(savedPlanPath)) {
      const saved: Plan = JSON.parse(fs.readFileSync(savedPlanPath, "utf-8"));
      const doneSteps = saved.steps.filter(s => s.status === "done").length;
      if (doneSteps > 0 && doneSteps < saved.steps.length) {
        // There are completed steps we can resume from — reset any in_progress steps to pending
        resumedPlan = {
          ...saved,
          steps: saved.steps.map(s => ({
            ...s,
            status: (s.status === "in_progress" ? "pending" : s.status) as any,
          })),
        };
        console.log(`[Autonomy/Hypothesis] Resuming interrupted plan for "${feature.title}" — ${doneSteps}/${saved.steps.length} steps already done`);
      }
    }
  } catch { /* non-fatal — fall through to fresh plan */ }

  // planA: resume from interrupted execution if available, else generate fresh
  const planA: Plan = resumedPlan ?? await generateFeaturePlan(feature.title, feature.description, { lastTestFailureContext, priorKnowledge, priorFailureCount: priorFailures });
  // planB: always a fresh alternative (different approach)
  const planB = await generateFeaturePlan(feature.title, feature.description, {
    lastTestFailureContext,
    alternativeHypothesis: true,
    previousApproach: planA.goal,
    priorKnowledge,
    priorFailureCount: priorFailures,
  });

  // --- Execute hypothesis A with its pre-built plan ---
  console.log(`[Autonomy/Hypothesis] Executing hypothesis A: "${planA.goal}"`);
  const resultA = await executeFeaturePlan(feature.id, feature.title, feature.description, {
    lastTestFailureContext,
    preBuildPlan: planA,
    featureAttemptCount,
  });

  const snapshotADir = resultA.filesModified.length > 0
    ? saveHypothesisSnapshot(resultA.filesModified, snapshotTagA)
    : "";

  const testA = resultA.success ? await runAcceptanceTest(feature.id) : null;
  // Quality-metric scoring: acceptance test (primary) + TSC delta (secondary) + build success (tertiary)
  const tscDeltaA = resultA.tscErrorsDelta ?? 0;
  const aScore = (testA?.passed ? 10000 : 0) + (tscDeltaA * 100) + (resultA.success ? 500 : 0);
  console.log(`[Autonomy/Hypothesis] A score: ${aScore} (test: ${testA?.passed ?? "skipped"}, tscDelta: ${tscDeltaA}, success: ${resultA.success})`);

  // Roll back A fully — restore modified files AND delete any newly created files
  rollbackHypothesisFull(resultA.filesModified);

  // --- Execute hypothesis B with its pre-built plan ---
  console.log(`[Autonomy/Hypothesis] Executing hypothesis B: "${planB.goal}"`);
  const resultB = await executeFeaturePlan(feature.id, feature.title, feature.description, {
    lastTestFailureContext,
    preBuildPlan: planB,
    featureAttemptCount,
  });

  if (resultB.filesModified.length > 0) {
    saveHypothesisSnapshot(resultB.filesModified, snapshotTagB);
  }

  const testB = resultB.success ? await runAcceptanceTest(feature.id) : null;
  const tscDeltaB = resultB.tscErrorsDelta ?? 0;
  const bScore = (testB?.passed ? 10000 : 0) + (tscDeltaB * 100) + (resultB.success ? 500 : 0);
  console.log(`[Autonomy/Hypothesis] B score: ${bScore} (test: ${testB?.passed ?? "skipped"}, tscDelta: ${tscDeltaB}, success: ${resultB.success})`);

  // --- Compare and commit winner — gate strictly on acceptance test pass ---
  const aPassed = testA?.passed === true;
  const bPassed = testB?.passed === true;

  if (!aPassed && !bPassed) {
    // Neither hypothesis passed acceptance — roll back B fully and escalate to Opus
    rollbackHypothesisFull(resultB.filesModified);
    console.log(`[Autonomy/Hypothesis] Neither hypothesis passed acceptance — escalating to Opus for: ${feature.title}`);
    logActivity("warning", `Both hypotheses failed acceptance — Opus escalation for: ${feature.title}`);

    try {
      const errorSummary = [
        resultA.error && `Hypothesis A error: ${resultA.error}`,
        resultB.error && `Hypothesis B error: ${resultB.error}`,
      ].filter(Boolean).join("\n");

      const opusResult = await executeFeaturePlan(feature.id, feature.title, feature.description, {
        lastTestFailureContext: `Both A/B hypotheses failed acceptance.\nPlan A: "${planA.goal}"\nPlan B: "${planB.goal}"\n${errorSummary}\nAttempt a completely different strategy.`,
        featureAttemptCount: (featureAttemptCount ?? 1) + 2, // Force max escalation for Opus fallback
      });
      return {
        ...opusResult,
        hypothesisChosen: "opus" as const,
        hypothesisAApproach: planA.goal,
        hypothesisBApproach: planB.goal,
      };
    } catch (opsErr: any) {
      console.log(`[Autonomy/Hypothesis] Opus escalation failed: ${opsErr.message}`);
      return { ...resultB, success: false, hypothesisChosen: "none" as const, error: "Both hypotheses and Opus escalation failed" };
    }
  }

  if (aPassed && !bPassed) {
    // Only A passed acceptance — roll back B, restore A
    rollbackHypothesisFull(resultB.filesModified);
    if (snapshotADir) restoreHypothesisSnapshot(snapshotADir);
    console.log(`[Autonomy/Hypothesis] Hypothesis A wins (only A passed acceptance) — "${planA.goal}"`);
    logActivity("success", `Hypothesis A chosen for: ${feature.title}`);
    return {
      ...resultA,
      success: true,
      hypothesisChosen: "A" as const,
      hypothesisAApproach: planA.goal,
      hypothesisBApproach: planB.goal,
    };
  }

  if (bPassed && !aPassed) {
    // Only B passed acceptance — keep B (already applied)
    console.log(`[Autonomy/Hypothesis] Hypothesis B wins (only B passed acceptance) — "${planB.goal}"`);
    logActivity("success", `Hypothesis B chosen for: ${feature.title}`);
    return {
      ...resultB,
      success: true,
      hypothesisChosen: "B" as const,
      hypothesisAApproach: planA.goal,
      hypothesisBApproach: planB.goal,
    };
  }

  // Both passed acceptance — pick winner by quality score (TSC delta is tiebreaker)
  if (aScore >= bScore) {
    // A wins on quality — roll back B, restore A
    rollbackHypothesisFull(resultB.filesModified);
    if (snapshotADir) restoreHypothesisSnapshot(snapshotADir);
    console.log(`[Autonomy/Hypothesis] Hypothesis A wins on quality (${aScore} vs ${bScore}) — "${planA.goal}"`);
    logActivity("success", `Hypothesis A chosen on quality for: ${feature.title}`);
    return {
      ...resultA,
      success: true,
      hypothesisChosen: "A" as const,
      hypothesisAApproach: planA.goal,
      hypothesisBApproach: planB.goal,
    };
  } else {
    // B wins on quality — keep B (already applied)
    console.log(`[Autonomy/Hypothesis] Hypothesis B wins on quality (${bScore} vs ${aScore}) — "${planB.goal}"`);
    logActivity("success", `Hypothesis B chosen on quality for: ${feature.title}`);
    return {
      ...resultB,
      success: true,
      hypothesisChosen: "B" as const,
      hypothesisAApproach: planA.goal,
      hypothesisBApproach: planB.goal,
    };
  }
}

async function runParallelFeatureCycle(): Promise<string> {
  const readyFeatures = getNextFeatures().slice(0, MAX_PARALLEL_FEATURES);
  if (readyFeatures.length === 0) {
    return "roadmap-complete";
  }

  console.log(`[Autonomy/Roadmap] Dispatching ${readyFeatures.length} independent feature(s) in parallel`);
  logActivity('info', `Roadmap: dispatching ${readyFeatures.length} feature(s) in parallel`);

  // Pre-screen stalled features BEFORE markFeatureInProgress to avoid incrementing attempt counts
  // on features that will be immediately skipped anyway.
  const preRoadmap = loadRoadmap();
  for (const feature of readyFeatures) {
    const pre = preRoadmap?.features.find(f => f.id === feature.id);
    if (!pre || (pre.attemptCount ?? 0) < STALL_SKIP_ATTEMPTS) continue;
    const existing = state.stalledFeatures.find(s => s.id === feature.id);
    const currentCycle = state.currentCycle;
    const lastSurgical = existing?.surgicalCycle ?? -STALL_SURGICAL_INTERVAL; // -interval so first encounter is always due
    const dueForSurgical = !existing || (currentCycle - lastSurgical) >= STALL_SURGICAL_INTERVAL;

    if (dueForSurgical) {
      // Pre-flight: if the test now passes without any build, mark done and skip
      if (testExists(feature.id)) {
        const quickCheck = await runAcceptanceTest(feature.id);
        if (quickCheck.passed && !quickCheck.skipped) {
          console.log(`[Autonomy/Stall] Feature "${feature.title}" passes — stall resolved, marking done`);
          logActivity('success', `Stall resolved: ${feature.id} passes test — marking done`);
          await markFeatureDone(feature.id);
          await setFeatureTestResult(feature.id, { passed: true, output: quickCheck.output, exitCode: quickCheck.exitCode, durationMs: quickCheck.durationMs });
          state.stalledFeatures = state.stalledFeatures.filter(s => s.id !== feature.id);
          continue; // don't mark in progress
        }
      }
      console.log(`[Autonomy/Stall] Feature "${feature.title}" — surgical retry (cycle ${currentCycle}, ${pre.attemptCount} prior attempts)`);
      logActivity('info', `Surgical retry: ${feature.title} (${pre.attemptCount} prior attempts) — Opus ultrathink + test script`);
      if (!existing) state.stalledFeatures.push({ id: feature.id, title: feature.title, attempts: pre.attemptCount ?? 0, surgicalCycle: currentCycle });
      else { existing.attempts = pre.attemptCount ?? 0; existing.surgicalCycle = currentCycle; }
      // Allow through — will mark in progress below and get Opus escalation from featureAttemptCount
    } else {
      // Not yet due for surgical retry — skip this cycle without incrementing attempt count
      logActivity('warning', `Stall hold: "${feature.title}" — surgical retry in ${STALL_SURGICAL_INTERVAL - (currentCycle - lastSurgical)} cycles`);
      if (!existing) {
        state.stalledFeatures.push({ id: feature.id, title: feature.title, attempts: pre.attemptCount ?? 0 });
        writeUserActionNeeded(
          `Feature stalled: ${feature.title}`,
          `"${feature.title}" (${feature.id}) has failed ${pre.attemptCount} times. A surgical retry with full test-script context will run automatically every ${STALL_SURGICAL_INTERVAL} cycles. Review the acceptance test at .sneebly/acceptance-tests/${feature.id}.sh if you'd like to intervene.`,
          `Fix the stalled feature by running: bash .sneebly/acceptance-tests/${feature.id}.sh`
        );
      } else {
        existing.attempts = pre.attemptCount ?? 0;
      }
      // Skip — do NOT mark in progress so attempt count stays stable
      continue;
    }
  }

  for (const feature of readyFeatures) {
    // Only mark features in progress that weren't already handled (done or still on stall hold)
    if (state.stalledFeatures.find(s => s.id === feature.id && s.surgicalCycle === undefined)) continue;
    if (loadRoadmap()?.features.find(f => f.id === feature.id)?.status === 'done') continue;
    await markFeatureInProgress(feature.id);
    activelyBuildingFeatureIds.add(feature.id);
  }

  // Re-load roadmap after markFeatureInProgress so attemptCounts are current
  const updatedRoadmapForStall = loadRoadmap();

  for (const feature of readyFeatures) {
    if (!activelyBuildingFeatureIds.has(feature.id)) continue;
    const live = updatedRoadmapForStall?.features.find(f => f.id === feature.id);
    if (!live) continue;
    const attempts = live.attemptCount ?? 1;

    if (attempts >= STALL_SKIP_ATTEMPTS) {
      // Feature is being built surgically — log and allow through (stall entry already set above)
      console.log(`[Autonomy/Stall] Surgical build: "${feature.title}" (attempt ${attempts}) — Opus escalation active`);
    } else if (attempts >= STALL_DOWNGRADE_ATTEMPTS && feature.complexity === "high") {
      // Downgrade complexity: multi-hypothesis path is too expensive for a stuck feature
      console.warn(`[Autonomy/Stall] Feature "${feature.title}" attempted ${attempts}x — downgrading complexity high→medium`);
      logActivity('warning', `Stall mitigation: downgrading ${feature.id} complexity high→medium after ${attempts} attempts`);
      feature.complexity = "medium";
    }
  }

  // Filter out any features that were skipped due to stall
  const activeFeatures = readyFeatures.filter(f => activelyBuildingFeatureIds.has(f.id));
  if (activeFeatures.length === 0) {
    console.log('[Autonomy/Stall] All ready features are stalled — running experiment cycle while waiting');
    return "no-ready-features";
  }

  const featureTasks = activeFeatures.map(async (feature): Promise<FeatureResult> => {
    console.log(`[Autonomy/Roadmap] Building feature: ${feature.title} (${feature.id})`);
    logActivity('thinking', `Building roadmap feature: ${feature.title}`);

    if (!testExists(feature.id)) {
      logActivity('info', `Generating acceptance test for: ${feature.title}`);
      try {
        const testPath = await generateAcceptanceTest(feature.id, feature.title, feature.description);
        await setFeatureTestPath(feature.id, testPath);
        logActivity('info', `Acceptance test ready: ${feature.id}`);
      } catch (testGenErr: unknown) {
        console.log(`[Autonomy/Roadmap] Could not generate acceptance test for ${feature.id}: ${(testGenErr as Error).message}`);
      }
    } else {
      console.log(`[Autonomy/Roadmap] Acceptance test already exists for ${feature.id} — skipping regeneration`);
    }

    // Pre-flight check: if the acceptance test already passes, the feature is already
    // implemented (possibly from a previous session). Mark it done without rebuilding.
    if (testExists(feature.id)) {
      const preFlightResult = await runAcceptanceTest(feature.id);
      if (preFlightResult.passed && !preFlightResult.skipped) {
        console.log(`[Autonomy/Roadmap] Feature "${feature.title}" already passes acceptance test — marking done without rebuild`);
        logActivity('success', `Feature ${feature.id} already implemented — marked done (pre-flight)`);
        await markFeatureDone(feature.id);
        await setFeatureTestResult(feature.id, {
          passed: true,
          output: preFlightResult.output,
          exitCode: preFlightResult.exitCode,
          durationMs: preFlightResult.durationMs,
        });
        activelyBuildingFeatureIds.delete(feature.id);
        return {
          featureId: feature.id,
          success: true,
          stepsCompleted: 0,
          filesModified: [],
          cost: 0,
          hypothesisChosen: "none" as const,
        };
      }
    }

    const lastTestFailureContext = feature.lastTestResult && !feature.lastTestResult.passed
      ? formatTestFailureContext(feature.id, feature.lastTestResult)
      : undefined;

    const isHighComplexity = feature.complexity === "high";
    const featureAttemptCount = (feature as RoadmapFeature).attemptCount ?? 1;

    const result = isHighComplexity
      ? await runMultiHypothesisFeature(feature, lastTestFailureContext, featureAttemptCount)
      : await executeFeaturePlan(feature.id, feature.title, feature.description, { lastTestFailureContext, featureAttemptCount });

    if (result.success) {
      logActivity('info', `Running acceptance test for: ${feature.title}`);
      const validationResult = await runAcceptanceTest(feature.id);

      await setFeatureTestResult(feature.id, {
        passed: validationResult.passed,
        output: validationResult.output,
        exitCode: validationResult.exitCode,
        durationMs: validationResult.durationMs,
      });

      if (validationResult.passed === true && !validationResult.skipped) {
        await markFeatureDone(feature.id);
        console.log(`[Autonomy/Roadmap] Feature "${feature.title}" done — acceptance test PASSED (${result.stepsCompleted} steps)`);
        logActivity('success', `Roadmap feature done: ${feature.title} (tests passed)`);
        writeFeatureCompletionSummary(feature, result);

        try {
          // Use the winning approach text based on which hypothesis was chosen
          const winningApproach =
            result.hypothesisChosen === "A" ? (result.hypothesisAApproach || "") :
            result.hypothesisChosen === "B" ? (result.hypothesisBApproach || "") :
            result.hypothesisChosen === "opus" ? "Opus escalation (both A/B failed)" :
            result.filesModified.slice(0, 5).join(", ");
          const approachLabel = result.hypothesisChosen
            ? `Hypothesis ${result.hypothesisChosen}: ${winningApproach.slice(0, 300)}`
            : `Standard build targeting: ${winningApproach}`;
          const qualityDelta = result.tscErrorsDelta !== undefined
            ? result.tscErrorsDelta
            : Math.round(((result.stepsCompleted || 0) / Math.max(1, 6)) * 10);
          recordFeatureSuccess(
            feature.id,
            feature.title,
            approachLabel,
            result.filesModified,
            qualityDelta,
            "feature"
          );
        } catch (kbErr: any) {
          console.log(`[Autonomy/Roadmap] Knowledge recording failed (non-fatal): ${kbErr.message}`);
        }

        // Reset stall tracking — real progress was made
        state.lastProgressAt = new Date().toISOString();
        state.cyclesSinceProgress = 0;
        // Remove from stalled list if it was previously stalled
        state.stalledFeatures = state.stalledFeatures.filter(s => s.id !== feature.id);

        // Auto-research: every 5 completed features, synthesize new conventions
        completedFeaturesThisSession += 1;
        if (shouldRunResearch(completedFeaturesThisSession)) {
          setImmediate(async () => {
            try {
              await runResearchCycle(completedFeaturesThisSession, "auto");
            } catch (rErr: any) {
              console.log(`[AutoResearch] Research cycle error (non-fatal): ${rErr.message}`);
            }
          });
        }
      } else {
        await resetFeatureStatus(feature.id);
        const failureCtx = validationResult.skipped
          ? `Acceptance test could not run for ${feature.id}: ${validationResult.skipReason}`
          : formatTestFailureContext(feature.id, validationResult);
        console.log(`[Autonomy/Roadmap] Feature "${feature.title}" built but acceptance test ${validationResult.skipped ? 'SKIPPED' : 'FAILED'} — not marking done`);
        logActivity('warning', `Roadmap feature ${feature.id}: build passed but acceptance test ${validationResult.skipped ? 'skipped (no script)' : 'failed'}`);
        result.success = false;
        result.error = failureCtx;
      }
    } else {
      await resetFeatureStatus(feature.id);
      console.log(`[Autonomy/Roadmap] Feature "${feature.id}" incomplete: ${result.error || "plan not completed"}`);
      logActivity('info', `Roadmap feature incomplete: ${feature.title}`);
    }

    activelyBuildingFeatureIds.delete(feature.id);
    return result;
  });

  const settled = await Promise.allSettled(featureTasks);
  // Log any rejected feature tasks so errors are never silently swallowed
  for (const r of settled) {
    if (r.status === "rejected") {
      console.error(`[Autonomy/Roadmap] Feature task REJECTED (unhandled throw):`, r.reason?.message || r.reason);
      logActivity('error', `Feature task threw: ${r.reason?.message || String(r.reason)}`);
    }
  }
  const successCount = settled.filter(
    (r): r is PromiseFulfilledResult<FeatureResult> => r.status === "fulfilled" && r.value.success
  ).length;

  console.log(`[Autonomy/Roadmap] Parallel cycle complete: ${successCount}/${readyFeatures.length} features completed`);

  // Post-build UI scan: if any client files were modified, regenerate spec and scan
  const allFilesModified = settled
    .filter((r): r is PromiseFulfilledResult<FeatureResult> => r.status === "fulfilled")
    .flatMap(r => r.value.filesModified || []);
  const hasClientChanges = allFilesModified.some(f =>
    f.startsWith("client/") || f.endsWith(".tsx") || f.endsWith(".jsx")
  );
  if (hasClientChanges) {
    await runPostBuildUiScan('runParallelFeatureCycle');
  }

  const updatedRoadmap = loadRoadmap();
  if (updatedRoadmap) {
    const doneCount = updatedRoadmap.features.filter(f => f.status === "done").length;
    const totalCount = updatedRoadmap.features.length;
    const pendingCount = updatedRoadmap.features.filter(f => f.status === "pending").length;
    const phaseMilestones = [
      { threshold: 0.5, label: "50% roadmap complete" },
      { threshold: 0.75, label: "75% roadmap complete" },
      { threshold: 1.0, label: "100% roadmap complete" },
    ];

    for (const milestone of phaseMilestones) {
      const needed = Math.ceil(totalCount * milestone.threshold);
      const prevDone = doneCount - successCount;
      if (prevDone < needed && doneCount >= needed) {
        console.log(`[Autonomy/Roadmap] Phase milestone reached: ${milestone.label} (${doneCount}/${totalCount})`);
        logActivity('success', `Roadmap milestone: ${milestone.label}`);
        writeUserActionNeeded(
          `Milestone: ${milestone.label}`,
          `${doneCount} of ${totalCount} roadmap features are now complete. ${pendingCount} features remain. Review NEEDS-ATTENTION.md for details on completed features, then resume the autonomy loop.`
        );
        state.paused = true;
        break;
      }
    }
  }

  return successCount > 0 ? "success" : "build-failed";
}

const STALL_ANALYSIS_INTERVAL_CYCLES = 3;
let lastStallAnalysisCycle = 0;

async function runStallRootCauseAnalysis(stallCycles: number): Promise<string> {
  const journal = getSessionJournal();
  const recentEntries = journal?.entries.slice(-12) ?? [];

  const shellLog = getShellLog(15);
  const shellSummary = shellLog.map(e => {
    const signal = e.blocked ? "SAFETY-BLOCKED" : (e.success ? "OK" : `FAILED(exit ${e.exitCode})`);
    return `  [${signal}] ${e.command?.slice(0, 80)} — ${e.stderrPreview?.slice(0, 100) || "no error"}`;
  }).join("\n");

  const tscSection = cachedTscErrorText
    ? `Current TypeScript errors:\n${cachedTscErrorText.split("\n").filter((l: string) => l.includes("error TS")).slice(0, 20).join("\n")}`
    : "No TypeScript errors currently.";

  const recentResults = recentEntries.map(e =>
    `Cycle ${e.cycle}: ${e.result}${e.error ? ` — ${e.error?.slice(0, 120)}` : ""} (step: ${e.stepDescription?.slice(0, 60) || "none"})`
  ).join("\n");

  const stalledList = state.stalledFeatures.map(s =>
    `  - ${s.title} (${s.attempts} attempts${s.downgradedAt ? ", downgraded" : ""})`
  ).join("\n");

  const roadmap = loadRoadmap();
  const inProgressFeatures = roadmap?.features.filter(f => f.status === "in_progress" || f.status === "pending").map(f => `  - ${f.id}: ${f.title}`).join("\n") || "  (none)";

  // Collect "last code written" — read the most recently modified server/client TS files
  let lastCodeWritten = "(no recent file edits found)";
  try {
    const srcDirs = ["server", "client/src", "shared"].map(d => path.join(process.cwd(), d));
    const recentFiles: { file: string; mtime: number }[] = [];
    for (const dir of srcDirs) {
      if (!fs.existsSync(dir)) continue;
      const walk = (d: string): void => {
        for (const entry of fs.readdirSync(d, { withFileTypes: true })) {
          const full = path.join(d, entry.name);
          if (entry.isDirectory()) walk(full);
          else if (/\.(ts|tsx)$/.test(entry.name)) {
            try {
              const stat = fs.statSync(full);
              recentFiles.push({ file: full, mtime: stat.mtimeMs });
            } catch {}
          }
        }
      };
      walk(dir);
    }
    recentFiles.sort((a, b) => b.mtime - a.mtime);
    const top3 = recentFiles.slice(0, 3);
    lastCodeWritten = top3.map(({ file }) => {
      const rel = path.relative(process.cwd(), file);
      try {
        const lines = fs.readFileSync(file, "utf-8").split("\n");
        const snippet = lines.slice(0, 60).join("\n");
        return `### ${rel} (first 60 lines)\n\`\`\`typescript\n${snippet}\n\`\`\``;
      } catch {
        return `### ${rel}\n(could not read)`;
      }
    }).join("\n\n");
  } catch {}

  const prompt = `You are Claude Opus, the senior architect for this codebase. The autonomous builder has STALLED for ${stallCycles} consecutive cycles with no feature completions. Diagnose the root cause and produce a targeted fix brief.

## Stall Summary
- Cycles without progress: ${stallCycles}
- Stalled features: ${stalledList || "  (none flagged yet)"}
- Features in queue: \n${inProgressFeatures}

## Recent Build Results (last 12 journal entries)
${recentResults || "(no entries)"}

## Recent Shell Command Outcomes (last 15 commands)
${shellSummary || "(no shell log)"}

## ${tscSection}

## Last Code Written (3 most recently modified files)
${lastCodeWritten}

## Your Task
1. Identify the PRIMARY root cause of the stall. Be specific — name the exact file, error, or command pattern.
2. Classify the cause: typescript-error | missing-package | safety-blocked-command | build-logic-error | acceptance-test-failure | other
3. Produce a concrete fix brief: what exact change needs to be made to unblock the next cycle.
4. If the TypeScript errors are the root cause, list the specific files/lines to fix.
5. If a safety-blocked command pattern is the cause, describe the safe alternative.

Respond in JSON:
{
  "rootCause": "short description",
  "causeType": "typescript-error | missing-package | safety-blocked-command | build-logic-error | acceptance-test-failure | other",
  "primaryFile": "the main file to fix, or null",
  "fixBrief": "concrete step-by-step description of what to change",
  "urgency": "critical | high | medium"
}`;

  try {
    console.log(`[Autonomy/Stall] Running structured root cause analysis (${stallCycles} cycles stalled)...`);
    const result = await callClaude(prompt, {
      model: "claude-opus-4-6",
      maxTokens: 2048,
      temperature: 0.2,
      agent: "stall-analyzer",
      task: "stall-root-cause",
      feature: "stall-analysis",
    });

    const parsed = extractJson(result.text);
    if (!parsed) return result.text.slice(0, 500);

    const summary = `[Root Cause Analysis]\nType: ${parsed.causeType || "unknown"}\nCause: ${parsed.rootCause || "unknown"}\nFile: ${parsed.primaryFile || "N/A"}\nUrgency: ${parsed.urgency || "unknown"}\n\nFix Brief:\n${parsed.fixBrief || "(no fix brief)"}`;
    console.log(`[Autonomy/Stall] Root cause identified: ${parsed.rootCause} (${parsed.causeType})`);

    const header = fs.existsSync(path.join(process.cwd(), "NEEDS-ATTENTION.md")) ? "" : "# NEEDS ATTENTION\n\n---\n\n";
    fs.appendFileSync(
      path.join(process.cwd(), "NEEDS-ATTENTION.md"),
      `${header}## Stall Root Cause Analysis — Cycle ${state.currentCycle} (${new Date().toISOString()})\n${summary}\n\n---\n\n`,
      "utf-8"
    );

    return summary;
  } catch (err: any) {
    console.log(`[Autonomy/Stall] Root cause analysis failed: ${err.message}`);
    return "";
  }
}

export function startAutonomyLoop(intervalMs = MIN_CYCLE_INTERVAL_MS): void {
  if (loopInterval) return;

  state.running = true;
  state.paused = false;
  state.currentCycle = 0;
  state.errors = [];
  currentJournal = createJournal();
  saveJournal(currentJournal);

  console.log(`[Autonomy] Starting loop (Opus plans, Sonnet builds, Opus reviews)`);

  initRoadmap().then(async roadmap => {
    console.log(`[Autonomy] Roadmap initialized: ${roadmap.features.length} features`);

    const reconciled = await reconcileWithReality();
    if (reconciled.marked.length > 0) {
      console.log(`[Autonomy] Reconciled roadmap: ${reconciled.marked.length} features already done, ${reconciled.remaining.length} remaining`);
      logActivity('info', `Roadmap reconciled: ${reconciled.marked.length} done, ${reconciled.remaining.length} remaining`);
    }

    const resolvedCount = await reconcileBlockedConstraints();
    if (resolvedCount > 0) {
      console.log(`[Autonomy] Auto-resolved ${resolvedCount} phantom blocked constraint(s)`);
    }

    // Recover features stuck in_progress from a previous server session.
    // Any feature still in_progress at startup was interrupted mid-build and must be reset.
    const stuckFeatures = roadmap.features.filter(f => f.status === "in_progress");
    if (stuckFeatures.length > 0) {
      console.log(`[Autonomy] Recovering ${stuckFeatures.length} stuck in_progress feature(s) → pending`);
      for (const f of stuckFeatures) {
        await resetFeatureStatus(f.id);
        console.log(`[Autonomy] Reset ${f.id} (${f.title}) to pending`);
      }
    }

    const updatedRoadmap = loadRoadmap();
    const doneCount = updatedRoadmap?.features.filter(f => f.status === "done").length ?? 0;
    const totalCount = updatedRoadmap?.features.length ?? 0;
    logActivity('info', `Roadmap: ${doneCount}/${totalCount} features done`);

    triggerRetroactiveAcceptanceTests(updatedRoadmap?.features ?? []).catch(err => {
      console.log(`[Autonomy] Retroactive acceptance tests failed (non-fatal): ${err.message}`);
    });
  }).catch(err => {
    console.log(`[Autonomy] Roadmap init failed (non-fatal): ${err.message}`);
  });

  async function dispatchCycle(): Promise<void> {
    if (state.paused) return;

    if (needsRegeneration()) {
      console.log("[Autonomy] GOALS.md changed — regenerating roadmap (awaiting completion)...");
      try {
        const regenerated = await generateRoadmap();
        await ensureAllFeatureTestPaths(regenerated);
        console.log(`[Autonomy] Roadmap regenerated: ${regenerated.features.length} features (test paths registered)`);
      } catch (err: unknown) {
        console.log(`[Autonomy] Roadmap regeneration failed: ${err instanceof Error ? err.message : String(err)}`);
      }
    }

    const roadmap = loadRoadmap();
    let result: string;

    if (roadmap && roadmap.features.length > 0) {
      const readyFeatures = getNextFeatures();
      if (readyFeatures.length > 0) {
        result = await runParallelFeatureCycle();
      } else {
        // No ready features found — run an in-cycle reconciliation before giving up.
        // This handles the startup race condition where reconcileWithReality() is still
        // running asynchronously when the first dispatchCycle fires at 15s.
        // Reconciling here ensures we pick up newly-done features and resolved constraints
        // before falling back to experiment/waiting mode.
        try {
          const reconciledNow = await reconcileBlockedConstraints();
          if (reconciledNow > 0) {
            console.log(`[Autonomy] In-cycle constraint reconciliation: ${reconciledNow} phantom constraint(s) resolved`);
          }
        } catch (reconcileErr: unknown) {
          console.log(`[Autonomy] In-cycle reconciliation failed (non-fatal): ${reconcileErr instanceof Error ? reconcileErr.message : String(reconcileErr)}`);
        }

        // Re-check for ready features after reconciliation
        const readyAfterReconcile = getNextFeatures();
        if (readyAfterReconcile.length > 0) {
          console.log(`[Autonomy] Reconciliation unblocked ${readyAfterReconcile.length} feature(s) — dispatching`);
          result = await runParallelFeatureCycle();
        } else {
          // Self-healing: detect orphaned in_progress features that aren't being actively built.
          // This happens when a build was interrupted (restart, merge, crash) mid-cycle.
          const orphanedFeatures = roadmap.features.filter(
            f => f.status === "in_progress" && !activelyBuildingFeatureIds.has(f.id)
          );
          if (orphanedFeatures.length > 0) {
            console.log(`[Autonomy] Self-healing: detected ${orphanedFeatures.length} orphaned in_progress feature(s) — resetting to pending`);
            logActivity('warning', `Self-healing: resetting ${orphanedFeatures.length} orphaned feature(s) to pending`);
            for (const f of orphanedFeatures) {
              await resetFeatureStatus(f.id);
              console.log(`[Autonomy] Self-healed: ${f.id} (${f.title}) → pending`);
            }
            // Now re-check — the reset features should now be ready
            const readyAfterSelfHeal = getNextFeatures();
            if (readyAfterSelfHeal.length > 0) {
              console.log(`[Autonomy] Self-heal unblocked ${readyAfterSelfHeal.length} feature(s) — dispatching`);
              result = await runParallelFeatureCycle();
            } else {
              result = "roadmap-waiting";
            }
          } else {
          const allDone = roadmap.features.every(f => f.status === "done");
          if (allDone) {
            console.log("[Autonomy] Roadmap complete — switching to experiment mode");
            if (!isExperimentRunning()) {
              const exp = await runExperiment();
              result = exp ? `experiment-${exp.status}` : "experiment-skipped";
              if (exp) {
                logActivity('info', `Experiment ${exp.status}: ${exp.hypothesis} (score delta: ${exp.comparison?.delta.score ?? "N/A"})`);
              }
            } else {
              result = "experiment-running";
            }
          } else {
            console.log("[Autonomy] Roadmap: no ready features (all blocked by deps or in_progress) — running experiment while waiting");
            if (!isExperimentRunning()) {
              try {
                const exp = await runExperiment();
                result = exp ? `experiment-${exp.status}` : "roadmap-waiting";
                if (exp && exp.status !== "skipped") {
                  logActivity('info', `Experiment while waiting: ${exp.status}: ${exp.hypothesis}`);
                }
              } catch {
                result = "roadmap-waiting";
              }
            } else {
              result = "experiment-running";
            }
          }
          } // closes } else { // no orphaned features — allDone branch
        }
      }
    } else {
      result = await runCycle();
    }

    state.lastCycleResult = result;
    state.lastCycleTime = new Date().toISOString();
    console.log(`[Autonomy] Cycle result: ${result}`);

    // Progress watchdog: the feature completion handler resets cyclesSinceProgress to 0
    // and updates lastProgressAt. If that happened within this cycle window, don't count it
    // as a stall cycle. Otherwise increment.
    const progressThisCycle = state.lastProgressAt !== null &&
      (Date.now() - new Date(state.lastProgressAt).getTime()) < 300_000;
    if (!progressThisCycle) {
      state.cyclesSinceProgress += 1;
    }
    if (state.cyclesSinceProgress >= STALL_ANALYSIS_THRESHOLD) {
      const cyclesSinceLastAnalysis = state.currentCycle - lastStallAnalysisCycle;
      if (cyclesSinceLastAnalysis >= STALL_ANALYSIS_INTERVAL_CYCLES) {
        lastStallAnalysisCycle = state.currentCycle;
        setImmediate(async () => {
          try {
            const analysis = await runStallRootCauseAnalysis(state.cyclesSinceProgress);
            if (analysis) {
              logActivity('error', `Stall root cause identified — see NEEDS-ATTENTION.md for fix brief`);
            }
          } catch (analysisErr: any) {
            console.log(`[Autonomy/Stall] Analysis error (non-fatal): ${analysisErr.message}`);
          }
        });
      }
    }
    if (state.cyclesSinceProgress >= STALL_CYCLES_THRESHOLD) {
      const stalledMsg = `No features completed in ${state.cyclesSinceProgress} consecutive cycles — stall detected. Flagged features: ${state.stalledFeatures.map(s => `${s.title} (${s.attempts}x)`).join(', ') || 'none yet'}`;
      console.warn(`[Autonomy/Stall] ${stalledMsg}`);
      logActivity('warning', stalledMsg);
    }

    try {
      const roadmap = loadRoadmap();
      if (roadmap) {
        const done = roadmap.features.filter(f => f.status === "done").length;
        const tested = roadmap.features.filter(f => f.lastTestResult).length;
        const passed = roadmap.features.filter(f => f.lastTestResult?.passed).length;
        const testPassRate = tested > 0 ? Math.round((passed / tested) * 100) : 0;
        const buildSuccessRate = result === "success" ? 100 : 0;
        // Call countTscErrors() here for a fresh, accurate count at recording time
        let freshTscErrors = cachedTscErrorCount;
        try { freshTscErrors = countTscErrors(); } catch { /* use cached */ }
        updateQualityHistory({ tscErrors: freshTscErrors, testPassRate, buildSuccessRate });
      }
    } catch {}
  }

  setTimeout(async () => {
    await dispatchCycle();
  }, 15000);

  loopInterval = setInterval(async () => {
    await dispatchCycle();
  }, intervalMs);
}

export function stopAutonomyLoop(): void {
  if (loopInterval) {
    clearInterval(loopInterval);
    loopInterval = null;
  }
  state.running = false;
  state.paused = false;
  state.stopRequested = true;
  console.log("[Autonomy] Loop stopped — stopRequested flag set");
}

export function pauseAutonomyLoop(): void {
  state.paused = true;
  console.log("[Autonomy] Loop paused");
}

export function resumeAutonomyLoop(): void {
  state.paused = false;
  state.errors = [];
  console.log("[Autonomy] Loop resumed");
}

export function getAutonomyState(): AutonomyState & { completionPercent: number; journalSummary?: any; experimentSummary?: any } {
  const journal = loadJournal();
  if (!state.lastCycleTime && journal && journal.entries.length > 0) {
    try {
      const last = journal.entries[journal.entries.length - 1];
      state.lastCycleTime = last.timestamp;
      state.lastCycleResult = last.result;
      state.currentCycle = last.cycle;
      state.totalCycles = journal.entries.length;
      state.filesModified = Array.from(new Set(journal.entries.flatMap(e => e.filesModified)));
    } catch {}
  }
  const journalSummary = journal ? {
    sessionId: journal.sessionId,
    startedAt: journal.startedAt,
    totalCost: journal.totalCost,
    totalFilesModified: journal.totalFilesModified,
    successCount: journal.successCount,
    failCount: journal.failCount,
    entryCount: journal.entries.length,
    allFilesModified: Array.from(new Set(journal.entries.flatMap(e => e.filesModified))),
    totalCycles: journal.entries.length,
  } : undefined;
  let experimentSummary: any;
  try {
    experimentSummary = getExperimentSummary();
  } catch {}
  return { ...state, completionPercent: getCompletionPercent(), journalSummary, experimentSummary };
}

export async function triggerSingleCycle(): Promise<string> {
  if (state.paused && state.errors.length >= MAX_ERRORS_BEFORE_PAUSE) {
    return "paused-safety-requires-resume";
  }
  if (state.paused) state.paused = false;
  const savedTime = lastCycleStartTime;
  lastCycleStartTime = 0;
  const result = await runCycle();
  if (result === "rate-limited") lastCycleStartTime = savedTime;
  state.lastCycleResult = result;
  state.lastCycleTime = new Date().toISOString();
  return result;
}

// ─── Dedicated TSC Error Fixer ────────────────────────────────────────────────
//
// Proactively runs `npx tsc --noEmit`, sends the full error output to Claude,
// and applies the generated fixes. Callable manually via API or from the monitor.

export async function fixTscErrors(): Promise<{
  fixed: boolean;
  errorsBefore: number;
  errorsAfter: number;
  filesModified: string[];
  diagnosis?: string;
}> {
  const errorsBefore = countTscErrors();

  if (errorsBefore === 0) {
    logActivity('success', 'TSC check: 0 errors — nothing to fix');
    return { fixed: true, errorsBefore: 0, errorsAfter: 0, filesModified: [] };
  }

  logActivity('thinking', `TSC fixer: ${errorsBefore} error(s) detected — sending to Claude for diagnosis`);

  // Extract unique affected files from the error output
  const errorLines = cachedTscErrorText.split("\n").filter(l => l.match(/error TS\d+/));
  const affectedFilePaths = [...new Set(
    errorLines.map(l => l.match(/^([^(]+)\(/)?.[1]?.trim()).filter(Boolean)
  )] as string[];

  // Read content of each affected file
  const fileContents = affectedFilePaths.slice(0, 12).map(f => {
    try {
      const abs = path.resolve(process.cwd(), f);
      const content = fs.readFileSync(abs, "utf-8");
      return `=== ${f} ===\n${content}`;
    } catch { return ""; }
  }).filter(Boolean).join("\n\n");

  // Also read shared schema and routes for cross-reference
  const schemaContent = readFileFull("shared/schema.ts");
  const routesSnippet = readFileFull("server/routes.ts").split("\n").slice(0, 100).join("\n");

  const prompt = `You are a TypeScript expert performing a focused error-fixing pass. Fix ALL of the TypeScript errors listed below.

## Full TypeScript Error Output (${errorsBefore} errors)
\`\`\`
${errorLines.slice(0, 80).join("\n")}
\`\`\`

## Affected Files (current content)
${fileContents}

## Project Context
=== shared/schema.ts (first 100 lines) ===
${schemaContent.split("\n").slice(0, 100).join("\n")}

=== server/routes.ts (first 100 lines) ===
${routesSnippet}

## Project Conventions (STRICT)
- ESM ONLY: import/export, never require()
- Database IDs: varchar("id").primaryKey().default(sql\`gen_random_uuid()\`)
- All DB tables in shared/schema.ts with Drizzle ORM
- TypeScript strict mode — no implicit any, no unused imports
- All AI calls use @anthropic-ai/sdk via SNEEBLY_ANTHROPIC_API_KEY

## Your Task
Fix EVERY error in the list above. For each affected file, output the complete corrected file content.

Respond ONLY with valid JSON (no markdown):
{
  "diagnosis": "Summary of what was wrong across all files",
  "fileChanges": [
    { "filePath": "relative/path/to/file.ts", "content": "COMPLETE corrected file content" }
  ]
}`;

  const result = await callClaude(prompt, {
    model: "claude-sonnet-4-5",
    maxTokens: 32000,
    agent: "tsc-fixer",
    task: "fix-ts-errors",
    feature: "tsc-fix",
    context: `Fix ${errorsBefore} TypeScript errors`,
    routerReason: "TSC fixer: targeted compilation error resolution",
  });

  logToDaily(`tsc-fixer: $${result.cost.toFixed(3)}`);

  const parsed = extractJson(result.text);
  if (!parsed?.fileChanges?.length) {
    logActivity('error', 'TSC fixer: Claude produced no file changes');
    return { fixed: false, errorsBefore, errorsAfter: errorsBefore, filesModified: [] };
  }

  const safePaths = getSafePaths();
  const neverModify = getNeverModifyPaths();
  const modified: string[] = [];

  for (const change of parsed.fileChanges) {
    if (!isPathSafe(change.filePath, safePaths, neverModify)) {
      console.log(`[TSC-Fixer] Blocked unsafe path: ${change.filePath}`);
      continue;
    }
    const fullPath = path.resolve(process.cwd(), change.filePath);
    // Backup before overwriting
    if (fs.existsSync(fullPath)) {
      const backupDir = path.join(process.cwd(), ".sneebly", "backups", "tsc-fixer");
      if (!fs.existsSync(backupDir)) fs.mkdirSync(backupDir, { recursive: true });
      const safeName = change.filePath.replace(/[\/\\]/g, "__");
      fs.copyFileSync(fullPath, path.join(backupDir, `${safeName}.${Date.now()}.bak`));
    }
    const dir = path.dirname(fullPath);
    if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(fullPath, change.content, "utf-8");
    modified.push(change.filePath);
    console.log(`[TSC-Fixer] Fixed: ${change.filePath}`);
  }

  const errorsAfter = countTscErrors();
  const fixed = errorsAfter < errorsBefore;

  if (fixed) {
    logActivity('success',
      `TSC fixer: ${errorsBefore} → ${errorsAfter} errors (fixed ${errorsBefore - errorsAfter}, ${modified.length} file(s) changed)`,
      parsed.diagnosis?.slice(0, 200),
      modified
    );
  } else {
    logActivity('warning',
      `TSC fixer ran but errors unchanged: ${errorsAfter}/${errorsBefore} remain`,
      parsed.diagnosis?.slice(0, 200),
      modified
    );
  }

  return { fixed, errorsBefore, errorsAfter, filesModified: modified, diagnosis: parsed.diagnosis };
}
